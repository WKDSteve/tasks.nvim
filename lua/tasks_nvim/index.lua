---@module 'tasks_nvim.index'
---@brief Render, write and verify the generated task overviews.
---@description
--- `<area>/ROADMAP/TASKS.md` is derived, never hand-written (concept section
--- 4.1): a `GENERATED` comment, a heading with the count, and a GFM table of
--- the open tasks sorted by status rank, prio, slug. The same tasks always
--- render to the same bytes, which is what makes `check` mode possible and
--- keeps the git diff quiet.
---
--- Key responsibilities:
---  - `render`: pure text for one area; nil when it has no open task
---  - `write_area` / `write_all`: write only when the bytes differ, remove a
---    stale file when the last open task is gone, or (`check = true`) only
---    report what would change
---  - `render_global`: the all-areas overview as text, for on-demand export;
---    nothing here ever writes `ALL/TASKS.md` (decision E2: it is not committed)
---
--- Not its job: finding tasks (`scan`) or any UI around the result.

local fsio = require("tasks_nvim.fsio")
local model = require("tasks_nvim.model")
local scan = require("tasks_nvim.scan")
local vault = require("tasks_nvim.vault")
local waits = require("tasks_nvim.waits")

local M = {}

local EN_DASH = "–"
local ELLIPSIS = "…"

---Version of the rendering: bump it with every change that renders the same tasks to other text (a summary rule, a
---column, a sort order). It stands in the marker line, so a check can tell an index another engine wrote from one
---that is out of date. `TESTS/tasks_index_render_version_spec.lua` turns red when the rendering changes without it.
M.RENDER_VERSION = 1

---The marker line the first line of every generated index starts with (with the render version in it).
M.GENERATED_MARK = ("<!-- GENERATED by tasks.nvim (:Tasks index, render %d) — do not edit; edit tasks/*.md -->"):format(
  M.RENDER_VERSION
)

M.GLOBAL_MARK =
  "<!-- GENERATED on demand (:Tasks list all --to=file:...) — never committed, do not edit; edit tasks/*.md -->"

---Whether `text` is a generated index: its first line is a `<!-- GENERATED` comment. The older marker
---(`... :MyPlugins tasks index ...`) counts too, so an index written by an earlier version is replaced, not
---refused. A file without the marker is somebody's own `TASKS.md` and is never overwritten or removed.
---@param text string
---@return boolean
function M.is_generated(text)
  return fsio.lf(text):sub(1, 15) == "<!-- GENERATED "
end

---The render version a generated index was written with: the number in its marker line, `0` for an index of an engine
---from before the versions (its marker has none).
---@param text string
---@return integer
function M.render_version_of(text)
  local first = fsio.lf(text):match("^[^\n]*") or ""
  return tonumber(first:match("^<!%-%- GENERATED by tasks%.nvim %(:Tasks index, render (%d+)%)"))
    or 0
end

---An index without what one engine renders differently from another: the marker line goes, and every task row keeps
---its cells up to the task link (status, prio, effort, title and file) but loses the summary after it. Two indexes with
---the same skeleton list the same tasks in the same order and state; only their summaries may differ.
---@param text string
---@return string
function M.skeleton(text)
  local out = {}
  for line in (fsio.lf(text) .. "\n"):gmatch("([^\n]*)\n") do
    if line:sub(1, 15) ~= "<!-- GENERATED " then
      out[#out + 1] = line:match("^(|.-%]%(tasks/[^)]*%) |)") or line
    end
  end
  return table.concat(out, "\n")
end

---Longest summary shown in a table cell, in characters.
M.MAX_SUMMARY = 160

---Longest title shown in a table cell, in characters: a generated index must stay far below the read limit, or it
---could not be read back (and so not regenerated) after a few huge titles.
M.MAX_TITLE = 200

---Most blockers named in one cell; the rest is counted.
M.MAX_BLOCKERS = 5

---@param s string
---@return string
local function cell(s)
  return fsio.md_cell(s)
end

---The text of a link `[text](target)`. Brackets are escaped so a title cannot
---open or close a link. A backslash in front of a bracket would swallow that
---escape (`\\[` is an escaped backslash and a live bracket), and one at the end
---would escape the closing `]` the caller adds; such runs are doubled, so the
---number of backslashes in front of every bracket stays odd and the text reads
---back as written.
---@param s string
---@return string
local function link_text(s)
  local text = fsio.double_runs(cell(s), "^[%[%]]", true)
  return (text:gsub("[%[%]]", "\\%0"))
end

---Percent-encode what would end a Markdown link target early or break the
---table row. A valid slug (`a-z0-9-`) never needs it; a file with an odd name
---still gets a row that parses.
---@param s string
---@return string
local function link_target(s)
  return (
    s:gsub('[%c%s()<>|\\%[%]`"#%%]', function(c)
      return ("%%%02X"):format(c:byte())
    end)
  )
end

---The link target of a task below `tasks/`: `<slug>.md`, or `<slug>/<slug>.md`
---for a folder task.
---@param task Tasks.Task
---@return string
local function task_link(task)
  local target = link_target(task.slug)
  return task.folder and (target .. "/" .. target .. ".md") or (target .. ".md")
end

---@param s string
---@param max integer
---@return string
local function truncate(s, max)
  if vim.fn.strchars(s) <= max then
    return s
  end
  return vim.fn.strcharpart(s, 0, max - 1) .. ELLIPSIS
end

---A summary is written beside its task file, but shown in `ROADMAP/TASKS.md`: a relative link or image in it
---(`./assets/x.png` of a folder task) is rebased to the folder of the task as seen from the index
---(`tasks/<slug>/assets/x.png`), or it points nowhere. URLs, `#anchors` and absolute paths stay as they are; a task
---outside `ROADMAP/` is left alone. `base` goes in front for an index that lies elsewhere (the all-areas overview:
---`<link_prefix><area>/ROADMAP/`). The last `/ROADMAP/` of the path counts: the vault's own folder may hold one too.
---@param text string
---@param path string  # the task file
---@param base string  # the path from the index file to the area's `ROADMAP/`, "" for the area's own index
---@return string
local function rebase_links(text, path, base)
  local dir = (path or ""):match("^.*/ROADMAP/(.*)/[^/]*$")
  if not dir or not text:find("](", 1, true) then
    return text
  end
  return (
    text:gsub("(%[[^%]]*%]%()([^)%s]+)(%))", function(open, target, close)
      if target:match("^[%a][%w+.-]*:") or target:match("^[/#<]") then
        return nil
      end
      return open .. base .. dir .. "/" .. target:gsub("^%./", "") .. close
    end)
  )
end

---@param task Tasks.Task
---@param max integer
---@param base? string  # see `rebase_links`; default "" (the area's own index)
---@return string
local function summary_cell(task, max, base)
  local text = truncate(rebase_links(task.summary, task.path, base or ""), max)
  if #task.blocked_by > 0 then
    local ids = {}
    for i, id in ipairs(task.blocked_by) do
      if i > M.MAX_BLOCKERS then
        ids[#ids + 1] = ("+%d weitere"):format(#task.blocked_by - M.MAX_BLOCKERS)
        break
      end
      ids[#ids + 1] = "`" .. truncate(id, M.MAX_TITLE) .. "`"
    end
    local note = "(blockiert durch " .. table.concat(ids, ", ") .. ")"
    text = text == "" and note or (text .. " " .. note)
  end
  -- Only a parked task that names a reason gets the note: every other row stays byte for byte what it was, so the
  -- indexes of a vault without the field are not stale.
  local key = waits.key_of(task)
  if key then
    local note = "(wartet auf `" .. key .. "`)"
    text = text == "" and note or (text .. " " .. note)
  end
  return text == "" and EN_DASH or cell(text)
end

---The tasks that appear in an index: in `ROADMAP/tasks/` with an open status.
---@param tasks Tasks.Task[]
---@return Tasks.Task[]
local function open_tasks(tasks)
  local out = {}
  for _, t in ipairs(tasks) do
    if t.location == "roadmap" and model.is_open_status(t.status) then
      out[#out + 1] = t
    end
  end
  return out
end

---Render one area's `ROADMAP/TASKS.md`.
---
---@param area string
---@param tasks Tasks.Task[]  the area's tasks (any status; only open ones are listed)
---@param opts? { max_summary?: integer }
---@return string|nil text  nil when the area has no open task (no file then)
---@return integer open     number of listed tasks
function M.render(area, tasks, opts)
  local max = (opts and opts.max_summary) or M.MAX_SUMMARY
  local open = model.sort(open_tasks(tasks))
  if #open == 0 then
    return nil, 0
  end
  local lines = {
    M.GENERATED_MARK,
    ("# %s — offene Tasks (%d)"):format(area, #open),
    "",
    "| Status | Prio | Effort | Task | Zusammenfassung |",
    "|---|---|---|---|---|",
  }
  for _, t in ipairs(open) do
    lines[#lines + 1] = ("| %s | %s | %s | [%s](tasks/%s) | %s |"):format(
      t.status,
      t.prio and tostring(t.prio) or EN_DASH,
      t.effort and cell(t.effort) or EN_DASH,
      link_text(truncate(t.title, M.MAX_TITLE)),
      task_link(t),
      summary_cell(t, max)
    )
  end
  return table.concat(lines, "\n") .. "\n", #open
end

---@class Tasks.IndexOpts : Tasks.ScanOpts
---@field check? boolean        # Report only, write and remove nothing.
---@field max_summary? integer
---@field scanned? { tasks: Tasks.Task[], errors: string[]|string|nil }  # The area was scanned by the caller just now: do not scan it again.

---Bring one area's index in line with its task files.
---
---`git` in `dir`, or `nil` and what it said.
---@param dir string
---@param args string[]
---@param stdin? string
---@return string|nil stdout
---@return string|nil err
local function git(dir, args, stdin)
  local res =
    vim.system(vim.list_extend({ "git", "-C", dir }, args), { text = true, stdin = stdin }):wait()
  if res.code ~= 0 then
    return nil, ("git %s: %s"):format(args[1], vim.trim(res.stderr or ""))
  end
  return res.stdout or ""
end

---The repository of the vault `root`: its top level and the vault's prefix in it (`""`, or `sub/dir/`).
---@param root string
---@return string|nil top
---@return string prefix_or_err
local function repo_of(root)
  local top, terr = git(root, { "rev-parse", "--show-toplevel" })
  if not top then
    return nil, tostring(terr)
  end
  return vim.trim(top), vim.trim(git(root, { "rev-parse", "--show-prefix" }) or "")
end

---Check out what rendering the index of `area` reads, from the staging area into `tmp`: the files at the top of the
---vault (its marker names extra areas) and the area's `ROADMAP/`. Nothing else: the rows hold the ids of blockers,
---not their titles, so no other area is read. `checkout-index --all` of the whole vault took ~15 s (about 8000
---files) and was too slow for a pre-commit check.
---@param top string
---@param prefix string
---@param area string
---@param tmp string
---@param skip? string  a path left out (a generated index in conflict: `checkout-index` refuses it)
---@return integer|nil files  how many files of the area's `ROADMAP/` there are
---@return string|nil err
local function checkout_area(top, prefix, area, tmp, skip)
  local roadmap = prefix .. area .. "/ROADMAP/"
  local out, lerr = git(top, { "ls-files", "-z", "--", ":(glob)" .. prefix .. "*", roadmap })
  if not out then
    return nil, lerr
  end
  local paths, seen, files = {}, {}, 0
  for path in out:gmatch("[^%z]+") do
    if path ~= skip and not seen[path] then
      seen[path] = true
      paths[#paths + 1] = path
      if path:sub(1, #roadmap) == roadmap then
        files = files + 1
      end
    end
  end
  vim.fn.mkdir(tmp, "p")
  if #paths > 0 then
    local _, cerr = git(
      top,
      { "checkout-index", "-z", "--stdin", "--prefix=" .. tmp .. "/" },
      table.concat(paths, "\0") .. "\0"
    )
    if cerr then
      return nil, cerr
    end
  end
  return files
end

---Regenerate the index of `area` from the staging area and stage the result, without touching the
---working tree. In a shared checkout the tree also holds another session's uncommitted tasks: an
---index written from it lists tasks the commit does not contain, which the pre-push gate refuses.
---
---The staging area, not `HEAD`, because it is what the next commit will hold, own new tasks included. Inside a
---`git commit` (a hook) the staging area is `$GIT_INDEX_FILE`, the one that commit writes: `git commit -- <paths>`
---builds its own from `HEAD` and those paths.
---
---With `opts.check` nothing is written or staged: the result says whether the staged index is the one the staged
---tasks render to (`unchanged`) or not (`stale`, with `reason` `missing`, `outdated`, `orphan` or `conflict`).
---@param area string
---@param opts? Tasks.IndexOpts
---@return Tasks.IndexResult|nil result `path` is relative to the repository
---@return string|nil err
function M.stage_area(area, opts)
  opts = opts or {}
  local root, rerr = vault.root(opts)
  if not root then
    return nil, rerr
  end
  local top, prefix = repo_of(root)
  if not top then
    return nil, prefix
  end
  local rel = prefix .. area .. "/ROADMAP/TASKS.md"

  -- `checkout-index --all` skips a path in conflict without a word: a task file in one would drop out of the
  -- index. A conflicted generated index is no input (it is what this run rewrites); anything else must be resolved.
  local unmerged_out, uerr = git(top, { "ls-files", "--unmerged", "-z" })
  if not unmerged_out then
    return nil, uerr
  end
  local unmerged, seen, index_unmerged = {}, {}, false
  for entry in unmerged_out:gmatch("[^%z]+") do
    local path = entry:match("^%d+ %x+ %d+\t(.+)$")
    if path == rel then
      index_unmerged = true
    elseif path and not seen[path] and not path:match("/ROADMAP/TASKS%.md$") then
      seen[path] = true
      unmerged[#unmerged + 1] = path
    end
  end
  if #unmerged > 0 then
    table.sort(unmerged)
    return nil,
      ("the staging area holds a conflict (an autostash that did not apply?): %s; resolve it, then run again"):format(
        table.concat(unmerged, ", ")
      )
  end

  -- What of the area goes into the commit besides the index. A `pull --rebase --autostash` whose stash conflicts
  -- leaves every other change of the tree staged, another session's claim among them: the index is then built from
  -- it, rightly so, and only this list shows the caller that the staging area holds more than they put there.
  local diff_out, derr =
    git(top, { "diff", "--cached", "--name-only", "-z", "--", prefix .. area .. "/" })
  if not diff_out then
    return nil, derr
  end
  local staged = {}
  for path in diff_out:gmatch("[^%z]+") do
    if path ~= rel then
      staged[#staged + 1] = path
    end
  end
  table.sort(staged)

  local tmp = vim.fn.tempname()
  local function run()
    local files, cerr = checkout_area(top, prefix, area, tmp, index_unmerged and rel or nil)
    if not files then
      return nil, cerr
    end
    -- The area's folder as `write_area` wants it: an area all of whose tasks are done has no `ROADMAP/` left
    -- staged, yet its index must still go. A name that is no area of the vault stays an error.
    if files == 0 and not vault.has_area(root, area) then
      return nil, "unknown area: " .. tostring(area)
    end
    local tmp_root = (tmp .. "/" .. prefix):gsub("/+$", "")
    vim.fn.mkdir(tmp_root .. "/" .. area .. "/ROADMAP", "p")
    local result, werr = M.write_area(
      area,
      vim.tbl_extend("force", opts, { root = tmp_root, check = opts.check == true })
    )
    if not result then
      return nil, werr
    end
    if opts.check then
      if index_unmerged then
        result.action, result.reason = "stale", "conflict"
      end
      result.path = rel
      result.staged = staged
      return result
    end
    local _, serr
    if index_unmerged and result.action == "unchanged" then
      -- `checkout-index` left the conflicted index out, and no open task asks for one: the conflict goes with it.
      result.action = "removed"
    end
    if result.action == "removed" then
      _, serr = git(top, { "update-index", "--force-remove", "--", rel })
    elseif result.action == "written" then
      -- `--path`: the same clean filter (line endings) `git add` of that path would apply.
      local blob, herr = git(top, { "hash-object", "-w", "--path=" .. rel, result.path })
      if not blob then
        return nil, herr
      end
      local entry = ("100644,%s,%s"):format(vim.trim(blob), rel)
      _, serr = git(top, { "update-index", "--add", "--cacheinfo", entry })
    end
    if serr then
      return nil, serr
    end
    result.path = rel
    result.staged = staged
    -- The tree keeps its index file on purpose, but `check` and the gate read the tree: say when the two part,
    -- or the next `check` reads as if this run had done nothing (2026-11-21, a linked worktree of the vault).
    -- The blob the tree's file would stage (same clean filter) against the staged one; a file missing on one side
    -- differs. No `git diff`: it refreshes the index and may wait on a pager or a lock.
    local tree_file = top .. "/" .. rel
    local tree_blob = vim.fn.filereadable(tree_file) == 1
        and vim.trim(git(top, { "hash-object", "--path=" .. rel, tree_file }) or "")
      or nil
    local staged_blob = git(top, { "rev-parse", "--verify", "--quiet", ":" .. rel })
    staged_blob = staged_blob and vim.trim(staged_blob) or nil
    result.tree_differs = tree_blob ~= staged_blob
    return result
  end
  local ran, result, err = pcall(run)
  vim.fn.delete(tmp, "rf")
  if not ran then
    return nil, tostring(result)
  end
  return result, err
end

---The areas whose generated index the staging area may have put out of step: those with a staged change below
---`<area>/ROADMAP/` against `HEAD`. Renames are split into a deletion and an addition, so `done` (a task leaves
---`ROADMAP/tasks/` for `Backlog/`) names the area it left.
---@param opts? Tasks.ScanOpts
---@return string[]|nil areas  sorted
---@return string|nil err
function M.staged_areas(opts)
  local root, rerr = vault.root(opts)
  if not root then
    return nil, rerr
  end
  local top, prefix = repo_of(root)
  if not top then
    return nil, prefix
  end
  -- `--cached` without a commit compares against the empty tree (a vault's first commit).
  local out, derr = git(top, {
    "diff",
    "--cached",
    "--name-only",
    "--no-renames",
    "-z",
    "--",
    prefix ~= "" and prefix or ".",
  })
  if not out then
    return nil, derr
  end
  local set, areas = {}, {}
  for path in out:gmatch("[^%z]+") do
    local area = path:sub(#prefix + 1):match("^([^/]+)/ROADMAP/")
    if
      area
      and not set[area]
      and vault.valid_area(area)
      and not area:match("^[._]")
      and not vault.SKIP[area]
    then
      set[area] = true
      areas[#areas + 1] = area
    end
  end
  table.sort(areas)
  return areas
end

---Who wants to know that an index file changed on disk (`M.on_write`).
---@type table<integer, fun(root: string, result: Tasks.IndexResult)>
local write_listeners = {}
local next_listener = 0

---Call `fn(root, result)` after `write_area` wrote or removed an index file (never in check mode, never for an
---unchanged file). For readers that keep something derived from the index, the tree badges of
---`tasks_nvim.integrations.tree_counts` for one. A listener that raises is skipped: a reader must not be able
---to fail a write that already happened.
---@param fn fun(root: string, result: Tasks.IndexResult)
---@return fun() remove
function M.on_write(fn)
  next_listener = next_listener + 1
  local id = next_listener
  write_listeners[id] = fn
  return function()
    write_listeners[id] = nil
  end
end

---@param root string
---@param result Tasks.IndexResult
local function announce(root, result)
  for _, fn in pairs(write_listeners) do
    pcall(fn, root, result)
  end
end

---`action` is `written`, `removed`, `unchanged`, or (check mode) `stale` with a
---`reason`: `missing` (no file, but open tasks), `outdated` (content differs),
---`orphan` (a file although no task is open). A directory that could not be
---walked is an error: a partial listing would write a wrong index.
---@param area string
---@param opts? Tasks.IndexOpts
---@return Tasks.IndexResult|nil result
---@return string|nil err
function M.write_area(area, opts)
  opts = opts or {}
  local root, rerr = vault.root(opts)
  if not root then
    return nil, rerr
  end
  if not vault.has_area(root, area) then
    return nil, "unknown area: " .. tostring(area)
  end
  local tasks, errors
  if opts.scanned then
    -- The caller (`check`) scanned this area a moment ago; parsing every task again is the cost.
    tasks, errors = opts.scanned.tasks, opts.scanned.errors
  else
    tasks, errors = scan.area(area, vim.tbl_extend("force", opts, { root = root }))
  end
  if not tasks then
    return nil, tostring(errors)
  end
  if type(errors) == "table" and #errors > 0 then
    return nil, "cannot list " .. area .. ": " .. errors[1]
  end
  -- A task file that could not be read has no status here: it would silently drop out of the index (or the index
  -- would be deleted as "no open task"), a locked or oversized file costing the area its overview.
  for _, t in ipairs(tasks) do
    if t.error_codes and vim.tbl_contains(t.error_codes, "unreadable") then
      return nil, ("cannot read %s: %s"):format(t.path, tostring(t.errors and t.errors[1]))
    end
  end

  local path = vault.index_path(root, area)
  local text, open = M.render(area, tasks, opts)
  ---@type Tasks.IndexResult
  local result = { area = area, path = path, open = open, action = "unchanged" }
  local current
  if fsio.is_file(path) then
    -- An index that exists but cannot be read is an error: it used to count as "missing" and was then overwritten.
    local text_read, read_err = fsio.read(path)
    if not text_read then
      return nil, ("cannot read %s: %s"):format(path, tostring(read_err))
    end
    current = text_read
  end
  if current ~= nil and not M.is_generated(current) then
    return nil,
      ("%s is not a generated index (no GENERATED marker): move or delete it, tasks.nvim will not overwrite it"):format(
        path
      )
  end

  if not text then
    if current ~= nil then
      if opts.check then
        result.action, result.reason = "stale", "orphan"
        return result
      end
      local ok, err = fsio.remove(path)
      if not ok then
        return nil, "cannot remove " .. path .. ": " .. tostring(err)
      end
      result.action = "removed"
      announce(root, result)
    end
    return result
  end

  if current ~= nil and fsio.lf(current) == text then
    return result
  end
  if opts.check then
    -- An index another engine wrote (an older or newer summary rule) is not out of date as long as it lists the same
    -- tasks in the same state: otherwise every session with another tasks.nvim finds the indexes of the others stale
    -- and regenerates them back, and the pre-push gate of the next one is red again.
    local theirs = current ~= nil and M.render_version_of(current) or nil
    if theirs ~= nil and theirs ~= M.RENDER_VERSION then
      result.other_render = theirs
      if M.skeleton(current) == M.skeleton(text) then
        return result
      end
    end
    result.action = "stale"
    result.reason = current == nil and "missing" or "outdated"
    return result
  end
  -- A checkout that uses CRLF keeps it: only the content changed, not the style.
  if current ~= nil and fsio.eol_of(current) == "\r\n" then
    text = text:gsub("\n", "\r\n")
  end
  local ok, err = fsio.write_atomic(path, text)
  if not ok then
    return nil, "cannot write " .. path .. ": " .. tostring(err)
  end
  result.action = "written"
  announce(root, result)
  return result
end

---@class Tasks.WriteAllOpts : Tasks.IndexOpts
---@field areas? string[]   # Only these areas (default: every area of the vault).

---`write_area` for every area (or only `opts.areas`). Best effort: one failing
---area does not stop the others (ERR-42); each failure is listed in `errors`.
---@param opts? Tasks.WriteAllOpts
---@return Tasks.IndexResult[]|nil results
---@return string[] errors
function M.write_all(opts)
  opts = opts or {}
  local root, rerr = vault.root(opts)
  if not root then
    return nil, { rerr }
  end
  local names = opts.areas
  if not names then
    names = {}
    for _, a in ipairs(vault.areas(root)) do
      names[#names + 1] = a.name
    end
  end
  local results, errors = {}, {}
  for _, name in ipairs(names) do
    local res, err = M.write_area(name, vim.tbl_extend("force", opts, { root = root }))
    if res then
      results[#results + 1] = res
    else
      errors[#errors + 1] = name .. ": " .. tostring(err)
    end
  end
  return results, errors
end

---@param tasks Tasks.Task[]
---@return string|nil oldest  earliest `updated` (else `created`) among the tasks
local function oldest_date(tasks)
  local oldest
  for _, t in ipairs(tasks) do
    local d = t.updated or t.created
    if d and model.is_date(d) and (oldest == nil or d < oldest) then
      oldest = d
    end
  end
  return oldest
end

---@class Tasks.GlobalOpts
---@field top? integer              # Rows in the cross-area list (default 20).
---@field areas? string[]           # Areas to list even when they have no open task.
---@field links? boolean            # Link to the area index / task files (default true).
---@field link_prefix? string       # Prefix of those links (default `../`, i.e. the file sits in `ALL/`).
---@field max_summary? integer

---Render the all-areas overview (concept section 4.2): one row per area with
---the count per status, the highest prio and the oldest update, then the top
---tasks across all areas. Returns text only -- the caller decides where it
---goes, and nothing here writes `ALL/TASKS.md`.
---@param tasks Tasks.Task[]
---@param opts? Tasks.GlobalOpts
---@return string text
---@return integer open  number of open tasks counted
function M.render_global(tasks, opts)
  opts = opts or {}
  local top = opts.top or 20
  local max = opts.max_summary or M.MAX_SUMMARY
  local links = opts.links ~= false
  local prefix = opts.link_prefix or "../"
  local open = model.sort(open_tasks(tasks))

  local by_area, order = {}, {}
  local function bucket(name)
    if not by_area[name] then
      by_area[name] = {}
      order[#order + 1] = name
    end
    return by_area[name]
  end
  for _, name in ipairs(opts.areas or {}) do
    bucket(name)
  end
  for _, t in ipairs(open) do
    local list = bucket(t.area)
    list[#list + 1] = t
  end
  table.sort(order)

  local with_tasks = 0
  for _, name in ipairs(order) do
    if #by_area[name] > 0 then
      with_tasks = with_tasks + 1
    end
  end

  local lines = {
    M.GLOBAL_MARK,
    ("# Offene Tasks — alle Bereiche (%d in %d Bereichen)"):format(#open, with_tasks),
    "",
    "## Pro Bereich",
    "",
    "| Bereich | doing | decision | blocked | open | parked | Gesamt | Prio | Ältester Stand |",
    "|---|---|---|---|---|---|---|---|---|",
  }
  for _, name in ipairs(order) do
    local list = by_area[name]
    local counts = {}
    local best
    for _, t in ipairs(list) do
      counts[t.status] = (counts[t.status] or 0) + 1
      if t.prio and (best == nil or t.prio < best) then
        best = t.prio
      end
    end
    local label = name
    if links then
      label = ("[%s](%s%s/ROADMAP/TASKS.md)"):format(name, prefix, link_target(name))
    end
    lines[#lines + 1] = ("| %s | %d | %d | %d | %d | %d | %d | %s | %s |"):format(
      label,
      counts.doing or 0,
      counts.decision or 0,
      counts.blocked or 0,
      counts.open or 0,
      counts.parked or 0,
      #list,
      best and tostring(best) or EN_DASH,
      oldest_date(list) or EN_DASH
    )
  end

  local shown = math.min(top, #open)
  lines[#lines + 1] = ""
  lines[#lines + 1] = ("## Top %d"):format(shown)
  lines[#lines + 1] = ""
  lines[#lines + 1] = "| Status | Prio | Effort | Bereich | Task | Zusammenfassung |"
  lines[#lines + 1] = "|---|---|---|---|---|---|"
  for i = 1, shown do
    local t = open[i]
    local title = link_text(truncate(t.title, M.MAX_TITLE))
    if links then
      title = ("[%s](%s%s/ROADMAP/tasks/%s)"):format(
        title,
        prefix,
        link_target(t.area),
        task_link(t)
      )
    end
    lines[#lines + 1] = ("| %s | %s | %s | %s | %s | %s |"):format(
      t.status,
      t.prio and tostring(t.prio) or EN_DASH,
      t.effort and cell(t.effort) or EN_DASH,
      cell(t.area),
      title,
      summary_cell(t, max, prefix .. link_target(t.area) .. "/ROADMAP/")
    )
  end
  return table.concat(lines, "\n") .. "\n", #open
end

return M
