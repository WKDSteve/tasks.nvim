-- TESTS/tasks_ci_own_spec.lua -- `tasks ci --own-since=<rev>`: in a shared vault only the findings of the areas a push
-- changes block it; another session's stale index or broken task is printed as foreign: and not counted.

---@diagnostic disable: need-check-nil, param-type-mismatch
-- Why: a value is bound with assert()/ok() in the same body, so a nil fails the spec at that line.

return function(H)
  local eq, ok, has, lacks = H.eq, H.ok, H.has, H.lacks
  local F = dofile(vim.fs.dirname(debug.getinfo(1, "S").source:sub(2)) .. "/fixture.lua")
  local ci = require("tasks_nvim.ci")
  local index = require("tasks_nvim.index")
  local cli = require("tasks_nvim.cli")

  local STALE = "<!-- GENERATED by tasks.nvim (:Tasks index) -- stand-in -->\n# left behind\n"

  ---A vault with a task in lib.nvim and one in cascade.nvim, indexes written.
  ---@return string root
  local function vault()
    local root = F.vault(H)
    F.task(H, root, "lib.nvim", "alpha", F.meta("Alpha", "open"), "\nMine.\n")
    F.task(H, root, "cascade.nvim", "beta", F.meta("Beta", "open"), "\nTheirs.\n")
    assert(index.write_all({ root = root }))
    return root
  end

  ---`changed_paths` as git would answer for a push that changed `paths`.
  local function changed(paths)
    return function(_, rev)
      eq(rev, "origin/main", "the rev is handed through")
      return paths
    end
  end
  local MINE =
    { "lib.nvim/ROADMAP/tasks/alpha.md", "lib.nvim/ROADMAP/TASKS.md", "_Telemetry/history/x.jsonl" }

  ---@param root string
  ---@param paths string[]|fun(): nil, string
  ---@param extra? table
  local function gate(root, paths, extra)
    local res = ci.run(vim.tbl_extend("force", {
      root = root,
      lint = false,
      own_since = "origin/main",
      changed_paths = type(paths) == "function" and paths or changed(paths),
    }, extra or {}))
    return res, table.concat(res.lines, "\n")
  end

  -- ── another session's stale index does not block ─────────────────────────
  local root = vault()
  H.write(root .. "/cascade.nvim/ROADMAP/TASKS.md", STALE)
  local res, text = gate(root, MINE)
  eq(res.code, 0, text)
  has(text, "own area(s): lib.nvim")
  has(text, "foreign: index: cascade.nvim is outdated")
  has(text, "2 finding(s) in areas this push does not touch", "check and index step each name it")
  has(text, "4 area(s) up to date, 1 foreign stale not counted")
  lacks(text, "index cascade.nvim --staged", "no fix line for another session's area")

  -- without --own-since every finding counts, as before (the runner's full gate)
  res = ci.run({ root = root, lint = false })
  eq(res.code, 1)
  ok(vim.tbl_contains(res.failed, "index"))

  -- ── an own stale index blocks ────────────────────────────────────────────
  root = vault()
  H.write(root .. "/lib.nvim/ROADMAP/TASKS.md", STALE)
  res, text = gate(root, MINE)
  eq(res.code, 1, text)
  ok(vim.tbl_contains(res.failed, "index"))
  has(text, "index: lib.nvim is outdated")
  has(text, "index lib.nvim --staged", "the fix line names the own area")

  -- ── rule errors follow the same line ─────────────────────────────────────
  root = vault()
  H.write(root .. "/cascade.nvim/ROADMAP/tasks/broken.md", "no frontmatter at all\n")
  assert(index.write_all({ root = root }))
  res, text = gate(root, MINE)
  eq(res.code, 0, text)
  has(text, "foreign: cascade.nvim/ROADMAP/tasks/broken.md")
  has(text, "check: 0 error(s)")
  res = gate(root, { "cascade.nvim/ROADMAP/tasks/broken.md" })
  eq(res.code, 1, "the push that brings the broken file is blocked by it")
  ok(vim.tbl_contains(res.failed, "check"))

  -- a rename out of an area makes that area own too (the paths come as a deletion and an addition)
  res = gate(root, { "cascade.nvim/ROADMAP/tasks/gone.md", "lib.nvim/Backlog/TASKS/gone.md" })
  eq(res.code, 1)

  -- ── everything counts when the gate cannot tell, or a global file changed ──
  root = vault()
  H.write(root .. "/cascade.nvim/ROADMAP/TASKS.md", STALE)
  res, text = gate(root, function()
    return nil, "bad revision"
  end)
  eq(res.code, 1, "an unreadable diff never makes the gate green")
  has(text, "bad revision -- every finding counts")
  res, text = gate(root, { "lib.nvim/ROADMAP/tasks/alpha.md", "area-groups.json" })
  eq(res.code, 1)
  has(text, "area-groups.json changed -- every finding counts")
  -- a file outside the areas that the gate does not read leaves the line where it is
  res = gate(root, { "TOOLS/scripts/other.py", "README.md" })
  eq(res.code, 0)

  -- ── md_lint reads only the own areas' indexes ─────────────────────────────
  root = vault()
  H.write(root .. "/TOOLS/scripts/md_lint.lua", "os.exit(0)\n")
  local linted = {}
  res, text = gate(root, MINE, {
    lint = true,
    run_lint = function(files)
      vim.list_extend(linted, files)
      return 0, ""
    end,
  })
  eq(res.code, 0, text)
  eq(#linted, 1, "one index linted")
  ok(linted[1]:match("lib%.nvim/ROADMAP/TASKS%.md$"), linted[1])
  has(text, "md_lint leaves out 1 index(es)")

  -- ── the real diff: <rev>...HEAD of the vault's repository ─────────────────
  root = vault()
  local function git(args)
    local r = vim.system(vim.list_extend({ "git", "-C", root }, args), { text = true }):wait()
    return vim.trim(r.stdout or ""), r.code
  end
  eq(select(2, git({ "init", "-q" })), 0)
  git({ "config", "core.autocrlf", "false" })
  git({ "config", "user.name", "t" })
  git({ "config", "user.email", "t@example.org" })
  git({ "config", "commit.gpgsign", "false" })
  git({ "add", "." })
  git({ "commit", "-q", "-m", "seed" })
  -- another session left a stale index on the base; this push changes only lib.nvim
  H.write(root .. "/cascade.nvim/ROADMAP/TASKS.md", STALE)
  git({ "add", "." })
  git({ "commit", "-q", "-m", "theirs" })
  local base = git({ "rev-parse", "HEAD" })
  F.task(H, root, "lib.nvim", "alpha", F.meta("Alpha renamed", "open"), "\nMine.\n")
  assert(index.write_all({ root = root, areas = { "lib.nvim" } }))
  git({ "add", "lib.nvim" })
  git({ "commit", "-q", "-m", "mine" })
  local paths = assert(ci.changed_paths(root, base))
  table.sort(paths)
  eq(paths, { "lib.nvim/ROADMAP/TASKS.md", "lib.nvim/ROADMAP/tasks/alpha.md" })
  eq(ci.changed_paths(root, "no-such-rev"), nil, "an unknown rev is an error")

  -- through the CLI, as the pre-push hook of the vault calls it
  local said = {}
  local function put(s)
    said[#said + 1] = s
  end
  local code = cli.run(
    { "ci", "--no-lint", "--own-since=" .. base, "--vault=" .. root },
    { out = put, err = put }
  )
  eq(code, 0, table.concat(said, "\n"))
  has(table.concat(said, "\n"), "foreign: index: cascade.nvim")
  said = {}
  code = cli.run({ "ci", "--no-lint", "--vault=" .. root }, { out = put, err = put })
  eq(code, 1, "the full gate still sees the stale index")
end
