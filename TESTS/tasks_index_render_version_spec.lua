-- TESTS/tasks_index_render_version_spec.lua -- the render version of ROADMAP/TASKS.md: an index another engine wrote
-- is not out of date while it lists the same tasks; the version must move with every change of the rendering.

---@diagnostic disable: need-check-nil, param-type-mismatch
-- Why: a value is bound with assert()/ok() in the same body, so a nil fails the spec at that line.

return function(H)
  local eq, ok, has = H.eq, H.ok, H.has
  local F = dofile(vim.fs.dirname(debug.getinfo(1, "S").source:sub(2)) .. "/fixture.lua")
  local ci = require("tasks_nvim.ci")
  local index = require("tasks_nvim.index")
  local model = require("tasks_nvim.model")

  -- ── guard: the rendering of a fixed set of tasks, per render version ──────
  -- Every body shape a summary rule looks at. When this hash changes, the same tasks render to other text: bump
  -- `index.RENDER_VERSION` and add the new hash here (keep the old ones: they document what each version rendered).
  local KNOWN = {
    [1] = "162be718541f3c7e19e2b9fd1c27679017b79c5e04090f1ad2a0c66c426fc9e4",
  }
  local function parsed(slug, meta, body)
    return model.parse_text(F.text(meta, body), {
      path = "/v/x/ROADMAP/tasks/" .. slug .. ".md",
      area = "x",
      id = "x/" .. slug,
    })
  end
  local tasks = {
    parsed(
      "para",
      F.meta("Paragraph", "open", { { "prio", "1" } }),
      "\nA first paragraph.\n\nMore.\n"
    ),
    parsed("boxes", F.meta("Checklist", "open"), "\n- [ ] one\n- [x] two\n"),
    parsed("learn", F.meta("Learning", "doing"), "\n## Lernpunkte\n\n- [ ] a point\n"),
    parsed("image", F.meta("Image", "open"), "\n![shot](assets/x.png)\n\nText after the image.\n"),
    parsed(
      "link",
      F.meta("Link", "open"),
      "\nSee [the other](other.md) and [web](https://x.org).\n"
    ),
    parsed(
      "field",
      F.meta("Field", "blocked", { { "summary", "From the field" }, { "blocked_by", "y/z" } }),
      ""
    ),
    parsed("pipe", F.meta('"A | pipe"', "open", { { "effort", "S" } }), "\nHas a | pipe.\n"),
    parsed("long", F.meta(("Long "):rep(60), "open"), "\n" .. ("word "):rep(80) .. "\n"),
  }
  local text = index.render("x", tasks)
  local hash = vim.fn.sha256(text)
  eq(
    hash,
    KNOWN[index.RENDER_VERSION],
    "the rendering changed: bump index.RENDER_VERSION and add this hash to KNOWN"
  )
  has(text, ", render " .. index.RENDER_VERSION .. ")", "the marker line names the render version")
  eq(index.render_version_of(text), index.RENDER_VERSION)
  eq(
    index.render_version_of("<!-- GENERATED by tasks.nvim (:Tasks index) — do not edit -->\n"),
    0
  )

  -- ── two engine states, one index ─────────────────────────────────────────
  local root = F.vault(H)
  F.task(
    H,
    root,
    "lib.nvim",
    "alpha",
    F.meta("Alpha", "open", { { "prio", "1" } }),
    "\nThe summary now.\n"
  )
  F.task(H, root, "lib.nvim", "beta", F.meta("Beta", "doing"), "\n- [ ] a box\n")
  assert(index.write_all({ root = root }))
  local path = root .. "/lib.nvim/ROADMAP/TASKS.md"
  local mine = H.read(path)

  ---The index as another engine would have written it: its own marker, other summaries.
  ---@param version string|nil  nil: the marker of an engine from before the versions
  local function as_other(version)
    local marker = version
        and ("<!-- GENERATED by tasks.nvim (:Tasks index, render %s) — do not edit; edit tasks/*.md -->"):format(
          version
        )
      or "<!-- GENERATED by tasks.nvim (:Tasks index) — do not edit; edit tasks/*.md -->"
    local body = mine:gsub("^[^\n]*\n", "")
    body = body:gsub("The summary now%.", "An older summary")
    return marker .. "\n" .. body
  end

  for _, version in ipairs({ "old", "2", "99" }) do
    H.write(path, as_other(version ~= "old" and version or nil))
    local res = assert(index.write_area("lib.nvim", { root = root, check = true }))
    eq(
      res.action,
      "unchanged",
      "another engine's summaries are not out of date (" .. version .. ")"
    )
    eq(res.other_render, version == "old" and 0 or tonumber(version))
    local gate = ci.run({ root = root, lint = false })
    eq(gate.code, 0, table.concat(gate.lines, "\n"))
    has(table.concat(gate.lines, "\n"), "rendered by another engine")
  end

  -- right after an engine update every index is another engine's: the gate says so in one line, not one per area
  H.write(path, as_other(nil))
  local cascade = root .. "/cascade.nvim/ROADMAP/TASKS.md"
  F.task(H, root, "cascade.nvim", "gamma", F.meta("Gamma", "open"), "\nTheirs.\n")
  assert(index.write_area("cascade.nvim", { root = root }))
  H.write(
    cascade,
    (H.read(cascade):gsub("^[^\n]*", "<!-- GENERATED by tasks.nvim (:Tasks index) -->"))
  )
  local gate = ci.run({ root = root, lint = false })
  eq(gate.code, 0, table.concat(gate.lines, "\n"))
  local info = vim.tbl_filter(function(l)
    return l:find("rendered by another engine", 1, true) ~= nil
  end, gate.lines)
  eq(#info, 1, table.concat(gate.lines, "\n"))
  has(info[1], "2 index(es)")
  has(info[1], "cascade.nvim (render 0), lib.nvim (render 0)")
  os.remove(root .. "/cascade.nvim/ROADMAP/tasks/gamma.md")
  assert(index.write_area("cascade.nvim", { root = root }))

  -- the same version with another summary is out of date: only another engine may differ in the summaries
  H.write(path, (mine:gsub("The summary now%.", "An older summary")))
  local res = assert(index.write_area("lib.nvim", { root = root, check = true }))
  eq(res.action, "stale")
  eq(res.reason, "outdated")

  -- another engine's index that lacks a task (or shows another state) is out of date all the same
  H.write(path, as_other(nil))
  F.task(H, root, "lib.nvim", "gamma", F.meta("Gamma", "open"), "\nNew.\n")
  res = assert(index.write_area("lib.nvim", { root = root, check = true }))
  eq(res.action, "stale", "a new task is a real change, whatever the engine")
  os.remove(root .. "/lib.nvim/ROADMAP/tasks/gamma.md")
  H.write(path, (as_other(nil):gsub("| open | 1 |", "| doing | 1 |")))
  res = assert(index.write_area("lib.nvim", { root = root, check = true }))
  eq(res.action, "stale", "another status is a real change")

  -- writing always writes this engine's version
  assert(index.write_all({ root = root }))
  ok(H.read(path) == mine, "index rewritten with this engine's marker and summaries")
end
